// Creates the native Android project (mobile/android) and applies Aduna's settings to it. Run by the GitHub workflow
// (.github/workflows/android.yml) and by `npm run build:debug|build:release`. Safe to run again.
//
// Environment (all optional):
//   GOOGLE_SERVICES_JSON   contents (or base64) of google-services.json from the Firebase console: needed for push
//   ADUNA_VERSION_CODE     integer, must go up with every Play Store upload (the workflow uses the run number)
//   ADUNA_VERSION_NAME     e.g. 1.0.7
//   ADUNA_KEYSTORE, ADUNA_KEYSTORE_PASSWORD, ADUNA_KEY_ALIAS, ADUNA_KEY_PASSWORD   release signing (see mobile/README.md)
import { existsSync, readFileSync, writeFileSync, cpSync, readdirSync, rmSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const android = join(root, 'android');
const app = join(android, 'app');
const run = (cmd, args, cwd = root) => { const r = spawnSync(cmd, args, { cwd, stdio: 'inherit', shell: process.platform === 'win32' }); if (r.status !== 0) { console.error(`\n${cmd} ${args.join(' ')} failed`); process.exit(r.status || 1); } };

// 1. the native project (generated by Capacitor, so Gradle files always match the Capacitor version)
if (!existsSync(android)) run('npx', ['cap', 'add', 'android']);
run('npx', ['cap', 'sync', 'android']);

// 2. icons: replace Capacitor's placeholder launcher icons, add the status-bar icon used by notifications
const res = join(app, 'src', 'main', 'res');
cpSync(join(root, 'overlay', 'res'), res, { recursive: true });
for (const d of readdirSync(res).filter((n) => n.startsWith('mipmap-'))) {
  for (const f of readdirSync(join(res, d))) if (/^ic_launcher(_round|_foreground)?\.webp$/.test(f)) rmSync(join(res, d, f)); // would clash with our .png
}

// 2b. keyboard: Capacitor's edge-to-edge margins only account for the status/navigation bars, so on Android 15+ the keyboard
// covered the message box. This MainActivity replaces that listener with one that also leaves room for the keyboard (IME).
{
  const javaDir = join(app, 'src', 'main', 'java', 'com', 'aduna', 'app');
  mkdirSync(javaDir, { recursive: true });
  writeFileSync(join(javaDir, 'MainActivity.java'), `package com.aduna.app;

import android.os.Bundle;
import android.view.View;
import android.view.ViewGroup;
import androidx.core.graphics.Insets;
import androidx.core.view.ViewCompat;
import androidx.core.view.WindowInsetsCompat;
import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {
    @Override
    public void onCreate(Bundle savedInstanceState) {
        registerPlugin(AdunaUpdater.class);
        super.onCreate(savedInstanceState);
        View web = getBridge().getWebView();
        ViewCompat.setOnApplyWindowInsetsListener(web, (v, w) -> {
            Insets bars = w.getInsets(WindowInsetsCompat.Type.systemBars() | WindowInsetsCompat.Type.displayCutout());
            Insets ime = w.getInsets(WindowInsetsCompat.Type.ime());
            ViewGroup.MarginLayoutParams mlp = (ViewGroup.MarginLayoutParams) v.getLayoutParams();
            mlp.leftMargin = bars.left;
            mlp.topMargin = bars.top;
            mlp.rightMargin = bars.right;
            mlp.bottomMargin = Math.max(bars.bottom, ime.bottom);
            v.setLayoutParams(mlp);
            return WindowInsetsCompat.CONSUMED;
        });
    }
}
`);

  writeFileSync(join(javaDir, 'AdunaUpdater.java'), `package com.aduna.app;

import android.content.Intent;
import android.content.pm.PackageInfo;
import android.net.Uri;
import android.os.Build;
import android.provider.Settings;
import androidx.core.content.FileProvider;
import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.CapacitorPlugin;
import java.io.File;
import java.io.FileOutputStream;
import java.io.InputStream;
import java.net.HttpURLConnection;
import java.net.URL;

// In-app updates: reports the installed version, and downloads + hands a new APK to Android's installer.
// Android only installs it over this app if it is signed with the same key, so a wrong file cannot replace the app.
@CapacitorPlugin(name = "AdunaUpdater")
public class AdunaUpdater extends Plugin {
    private volatile boolean busy = false;

    @PluginMethod
    public void getVersion(PluginCall call) {
        try {
            PackageInfo pi = getContext().getPackageManager().getPackageInfo(getContext().getPackageName(), 0);
            long code = Build.VERSION.SDK_INT >= 28 ? pi.getLongVersionCode() : pi.versionCode;
            JSObject r = new JSObject();
            r.put("versionCode", code);
            r.put("versionName", pi.versionName);
            call.resolve(r);
        } catch (Exception e) {
            call.reject("version");
        }
    }

    @PluginMethod
    public void install(PluginCall call) {
        final String url = call.getString("url", "");
        if (!url.startsWith("https://")) { call.reject("bad_url"); return; }
        if (Build.VERSION.SDK_INT >= 26 && !getContext().getPackageManager().canRequestPackageInstalls()) {
            Intent s = new Intent(Settings.ACTION_MANAGE_UNKNOWN_APP_SOURCES, Uri.parse("package:" + getContext().getPackageName()));
            s.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            getContext().startActivity(s);
            call.reject("permission");
            return;
        }
        if (busy) { call.reject("busy"); return; }
        busy = true;
        new Thread(() -> {
            try {
                File dir = new File(getContext().getCacheDir(), "updates");
                dir.mkdirs();
                File apk = new File(dir, "aduna-update.apk");
                HttpURLConnection c = (HttpURLConnection) new URL(url).openConnection();
                c.setConnectTimeout(15000);
                c.setReadTimeout(30000);
                c.setInstanceFollowRedirects(true);
                if (c.getResponseCode() != 200) throw new Exception("http " + c.getResponseCode());
                String ct = c.getContentType();
                if (ct != null && (ct.toLowerCase().startsWith("text/") || ct.toLowerCase().contains("json"))) throw new Exception("not_apk");
                long total = c.getContentLengthLong();
                long done = 0;
                int lastPct = -1;
                try (InputStream in = c.getInputStream(); FileOutputStream out = new FileOutputStream(apk)) {
                    byte[] buf = new byte[65536];
                    int n;
                    while ((n = in.read(buf)) > 0) {
                        out.write(buf, 0, n);
                        done += n;
                        int pct = total > 0 ? (int) (done * 100 / total) : -1;
                        if (pct != lastPct) { lastPct = pct; JSObject p = new JSObject(); p.put("percent", pct); notifyListeners("progress", p); }
                    }
                }
                if (total > 0 && done != total) { apk.delete(); throw new Exception("incomplete"); }
                try (java.io.FileInputStream head = new java.io.FileInputStream(apk)) {
                    byte[] m = new byte[4];
                    if (head.read(m) != 4 || m[0] != 0x50 || m[1] != 0x4B || m[2] != 3 || m[3] != 4) { apk.delete(); throw new Exception("not_apk"); }
                }
                try (java.io.RandomAccessFile raf = new java.io.RandomAccessFile(apk, "r")) { // an APK is a zip: its end record must be there, or the file is cut off
                    long len = raf.length();
                    int n = (int) Math.min(len, 65557);
                    byte[] t = new byte[n];
                    raf.seek(len - n);
                    raf.readFully(t);
                    boolean ok = false;
                    for (int k = n - 22; k >= 0 && !ok; k--) ok = t[k] == 0x50 && t[k + 1] == 0x4B && t[k + 2] == 5 && t[k + 3] == 6;
                    if (!ok) { apk.delete(); throw new Exception("not_apk"); }
                }
                Uri uri = FileProvider.getUriForFile(getContext(), getContext().getPackageName() + ".fileprovider", apk);
                Intent i = new Intent(Intent.ACTION_VIEW);
                i.setDataAndType(uri, "application/vnd.android.package-archive");
                i.addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION | Intent.FLAG_ACTIVITY_NEW_TASK);
                getContext().startActivity(i);
                call.resolve();
            } catch (Exception e) {
                String why = String.valueOf(e.getMessage());
                call.reject(why.equals("not_apk") || why.equals("incomplete") ? why : "download_failed");
            } finally {
                busy = false;
            }
        }).start();
    }
}
`);
}

// 3. manifest: calls need camera + microphone, notifications need the Android 13+ permission, and the Firebase defaults
const manifestPath = join(app, 'src', 'main', 'AndroidManifest.xml');
let m = readFileSync(manifestPath, 'utf8');
if (!m.includes('<!-- aduna -->')) {
  const perms = `    <!-- aduna -->
    <uses-permission android:name="android.permission.CAMERA" />
    <uses-permission android:name="android.permission.RECORD_AUDIO" />
    <uses-permission android:name="android.permission.MODIFY_AUDIO_SETTINGS" />
    <uses-permission android:name="android.permission.POST_NOTIFICATIONS" />
    <uses-feature android:name="android.hardware.camera" android:required="false" />
    <uses-feature android:name="android.hardware.microphone" android:required="false" />
`;
  const meta = `        <meta-data android:name="com.google.firebase.messaging.default_notification_icon" android:resource="@drawable/ic_stat_icon" />
        <meta-data android:name="com.google.firebase.messaging.default_notification_color" android:resource="@color/aduna_notification" />
        <meta-data android:name="com.google.firebase.messaging.default_notification_channel_id" android:value="messages" />
`;
  if (!/<application[\s>]/.test(m) || !m.includes('</application>')) { console.error('Unexpected AndroidManifest.xml; not patching it.'); process.exit(1); }
  m = m.replace(/(\s*)<application/, `\n${perms}$1<application`).replace('</application>', `${meta}    </application>`);
  m = m.replace('android:allowBackup="true"', 'android:allowBackup="false"'); // keep the chat session out of device backups
  writeFileSync(manifestPath, m);
}


// install permission for in-app updates (added separately so projects made by an earlier version get it too)
{
  let mm = readFileSync(manifestPath, 'utf8');
  if (!mm.includes('REQUEST_INSTALL_PACKAGES')) {
    mm = mm.replace(/(\s*)<application/, `\n    <uses-permission android:name="android.permission.REQUEST_INSTALL_PACKAGES" />$1<application`);
    writeFileSync(manifestPath, mm);
  }
}

// 4. version + release signing, appended to the module's build.gradle (a second android {} block merges with the first)
const gradlePath = join(app, 'build.gradle');
let g = readFileSync(gradlePath, 'utf8');
// drop any block from an earlier run (it is always last in the file) so a fixed version replaces it
const marker = g.indexOf('\n// aduna:');
if (marker !== -1) g = g.slice(0, marker) + '\n';
{
  g += `
// aduna: version and release signing come from the environment (see mobile/README.md)
android {
    defaultConfig {
        versionCode = Integer.parseInt(System.getenv("ADUNA_VERSION_CODE") ?: "1")
        versionName = System.getenv("ADUNA_VERSION_NAME") ?: "1.0"
    }
    if (System.getenv("ADUNA_KEYSTORE")) {
        signingConfigs {
            release {
                storeFile file(System.getenv("ADUNA_KEYSTORE"))
                storePassword System.getenv("ADUNA_KEYSTORE_PASSWORD")
                keyAlias System.getenv("ADUNA_KEY_ALIAS")
                keyPassword System.getenv("ADUNA_KEY_PASSWORD")
            }
        }
        buildTypes {
            release { signingConfig signingConfigs.release }
        }
    }
}
`;
  writeFileSync(gradlePath, g);
}

// 5. Firebase config (the Capacitor template applies the google-services plugin only when this file exists)
const localGs = join(root, 'google-services.json'); // for builds on your own computer: put the file here
const gs = (process.env.GOOGLE_SERVICES_JSON || (existsSync(localGs) ? readFileSync(localGs, 'utf8') : '')).trim();
const gsPath = join(app, 'google-services.json');
if (gs) {
  const text = gs.startsWith('{') ? gs : Buffer.from(gs, 'base64').toString('utf8');
  try { JSON.parse(text); } catch { console.error('GOOGLE_SERVICES_JSON is not valid JSON (or base64 of it).'); process.exit(1); }
  mkdirSync(app, { recursive: true });
  writeFileSync(gsPath, text);
  console.log('google-services.json written: push notifications will work in this build.');
} else if (!existsSync(gsPath)) {
  console.warn('\n!! No google-services.json: the app will build and run, but it cannot register for push notifications.\n   Add it as the GOOGLE_SERVICES_JSON secret (see mobile/README.md).\n');
}
console.log('Android project ready in mobile/android');
